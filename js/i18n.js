  var current = "en";

  function fill(str, vars) {
    return String(str).replace(/\{(\w+)\}/g, function (m, k) { return vars && vars[k] != null ? vars[k] : m; });
  }

  function lookup(key) {
    var table = S[current] || S.en;
    return table[key] != null ? table[key] : S.en[key] != null ? S.en[key] : key;
  }

  /* Plain text. */
  function t(key, vars) { return fill(lookup(key), vars); }

  /* HTML: the template is escaped, the values are inserted as given (callers escape them). */
  function th(key, vars) {
    var esc = function (s) { return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;"); };
    return fill(esc(lookup(key)), vars);
  }

  function detect() {
    var langs = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || "en"]);
    for (var i = 0; i < langs.length; i++) {
      var l = String(langs[i]);
      if (S[l]) return l;
      var base = l.split("-")[0];
      if (base === "pt") return "pt-BR";
      if (S[base]) return base;
    }
    return "en";
  }

